package names

import "testing"

// Имена вымышленные (П8).
func TestKey(t *testing.T) {
	cases := []struct{ a, b string }{
		{"Тестов Иван", "ИВАН ТЕСТОВ"},               // регистр и порядок слов
		{"Тестов Семён", "тестов семен"},             // ё
		{"Әбдіқалықов Нұрбек", "Абдикалыков Нурбек"}, // казахские буквы
		{"Testov Ivan", "Тестов Иван"},               // латиница
		{"Zhaksylykov Shyngys", "Жаксылыков Шынгыс"}, // сочетания букв
		{"Тестов  Иван,", "Тестов Иван"},             // лишние знаки и пробелы
	}
	for _, c := range cases {
		if Key(c.a) != Key(c.b) {
			t.Fatalf("%q → %q, %q → %q — должны совпасть", c.a, Key(c.a), c.b, Key(c.b))
		}
	}
	if Key("Тестов Иван") == Key("Тестов Пётр") {
		t.Fatal("разные имена дали один ключ")
	}
	if Key("Тестов Иван ЧС!") != Key("Тестов Иван") || Key(" ЧС! Чёрный список ") != "" {
		t.Fatalf("служебные слова в ключе: %q, %q", Key("Тестов Иван ЧС!"), Key(" ЧС! Чёрный список "))
	}
	if Key("  ,. ") != "" {
		t.Fatalf("пустое имя: %q", Key("  ,. "))
	}
}

func TestSimilar(t *testing.T) {
	yes := [][2]string{
		{"Тестов Иван", "Тестов Иван Петрович"},  // у одного есть отчество
		{"Тестов Иван", "Тестов Иваан"},          // одна лишняя буква
		{"Жаксылыков Ильяс", "Жаксылыков Ильяз"}, // одна буква отличается
	}
	no := [][2]string{
		{"Тестов Иван", "Тестов Иван"},                    // одинаковые — это не «похожие», а «те же»
		{"Тестов Иван", "Тестов Пётр"},                    // однофамильцы с разными именами — разные люди
		{"Тестов Иван", "Примеров Иван"},                  // тёзки
		{"Ким Ли", "Ким Лю"},                              // короткие слова — одна буква не повод
		{"Тестов Иван Петрович", "Тестов Иван Сергеевич"}, // разные отчества
	}
	for _, c := range yes {
		if !Similar(Key(c[0]), Key(c[1])) {
			t.Fatalf("%q и %q — похожи", c[0], c[1])
		}
	}
	for _, c := range no {
		if Similar(Key(c[0]), Key(c[1])) {
			t.Fatalf("%q и %q — не похожи", c[0], c[1])
		}
	}
}
